package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// ServiceConfig 服务配置
type ServiceConfig struct {
	ServiceName      string
	ServiceNameLower string
	ServiceNameUpper string
	ServiceNameTitle string
	Description      string
	Version          string
	Author           string
	Features         []string
}

// 模板文件映射
var templateFiles = map[string]string{
	"cmd/service/main.go.tmpl":           "cmd/{{.ServiceNameLower}}/main.go",
	"cmd/service/wire_gen.go.tmpl":       "cmd/{{.ServiceNameLower}}/wire_gen.go",
	"cmd/service/wire.go.tmpl":           "cmd/{{.ServiceNameLower}}/wire.go",
	"internal/biz/biz.go.tmpl":           "internal/biz/biz.go",
	"internal/biz/service.go.tmpl":       "internal/biz/{{.ServiceNameLower}}.go",
	"internal/conf/conf.proto.tmpl":      "internal/conf/conf.proto",
	"internal/conf/conf.pb.go.tmpl":      "internal/conf/conf.pb.go",
	"internal/data/data.go.tmpl":         "internal/data/data.go",
	"internal/data/service.go.tmpl":      "internal/data/{{.ServiceNameLower}}.go",
	"internal/data/models/model.go.tmpl": "internal/data/models/{{.ServiceNameLower}}.go",
	"internal/server/grpc.go.tmpl":       "internal/server/grpc.go",
	"internal/server/server.go.tmpl":     "internal/server/server.go",
	"internal/service/service.go.tmpl":   "internal/service/service.go",
	"internal/service/handler.go.tmpl":   "internal/service/{{.ServiceNameLower}}.go",
	"api/service/proto.tmpl":             "../../../api/service/{{.ServiceNameLower}}/v1/{{.ServiceNameLower}}.proto",
	"api/service/err_proto.tmpl":         "../../../api/service/{{.ServiceNameLower}}/v1/{{.ServiceNameLower}}_error.proto",
}

func main() {
	if len(os.Args) < 2 {
		fmt.Println("Usage: service-gen <service-name> [options]")
		fmt.Println("Options:")
		fmt.Println("  --description=<description>  Service description")
		fmt.Println("  --version=<version>          Service version")
		fmt.Println("  --author=<author>            Author name")
		fmt.Println("  --features=<features>        Comma-separated list of features (grpc,http,redis,mysql)")
		os.Exit(1)
	}

	serviceName := os.Args[1]
	config := parseConfig(serviceName, os.Args[2:])

	// 创建服务目录
	serviceDir := filepath.Join("..", "..", "app", "service", config.ServiceNameLower)
	if err := os.MkdirAll(serviceDir, 0755); err != nil {
		fmt.Printf("Error creating service directory: %v\n", err)
		os.Exit(1)
	}

	// 生成模板文件
	if err := generateFiles(config, serviceDir); err != nil {
		fmt.Printf("Error generating files: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Service %s generated successfully!\n", config.ServiceName)
	fmt.Printf("Directory: %s\n", serviceDir)
	fmt.Println("\nNext steps:")
	fmt.Println("1. Navigate to the service directory")
	fmt.Println("2. Run 'make gen' to generate proto files")
	fmt.Println("3. Run 'go mod tidy' to install dependencies")
	fmt.Println("4. Run 'make build' to build the service")
}

func parseConfig(serviceName string, args []string) *ServiceConfig {
	config := &ServiceConfig{
		ServiceName:      serviceName,
		ServiceNameLower: strings.ToLower(serviceName),
		ServiceNameUpper: strings.ToUpper(serviceName),
		ServiceNameTitle: strings.Title(serviceName),
		Description:      fmt.Sprintf("%s service", serviceName),
		Version:          "v1",
		Author:           "Generated by service-gen",
		Features:         []string{"grpc", "redis", "mysql"},
	}

	for _, arg := range args {
		if strings.HasPrefix(arg, "--description=") {
			config.Description = strings.TrimPrefix(arg, "--description=")
		} else if strings.HasPrefix(arg, "--version=") {
			config.Version = strings.TrimPrefix(arg, "--version=")
		} else if strings.HasPrefix(arg, "--author=") {
			config.Author = strings.TrimPrefix(arg, "--author=")
		} else if strings.HasPrefix(arg, "--features=") {
			config.Features = strings.Split(strings.TrimPrefix(arg, "--features="), ",")
		}
	}

	return config
}

func generateFiles(config *ServiceConfig, outputDir string) error {
	// 创建模板目录
	templateDir := filepath.Join("templates")
	if _, err := os.Stat(templateDir); os.IsNotExist(err) {
		return fmt.Errorf("template directory not found: %s", templateDir)
	}

	for templatePath, outputPath := range templateFiles {
		// 构建完整的模板路径
		fullTemplatePath := filepath.Join(templateDir, templatePath)

		// 检查模板文件是否存在
		if _, err := os.Stat(fullTemplatePath); os.IsNotExist(err) {
			fmt.Printf("Template file not found: %s, skipping\n", fullTemplatePath)
			continue
		}

		// 构建输出路径
		tmpl, err := template.New(filepath.Base(templatePath)).ParseFiles(fullTemplatePath)
		if err != nil {
			return fmt.Errorf("error parsing template %s: %v", fullTemplatePath, err)
		}

		// 替换模板变量
		outputPath = replaceVariables(outputPath, config)
		fullOutputPath := filepath.Join(outputDir, outputPath)

		// 创建输出目录
		if err := os.MkdirAll(filepath.Dir(fullOutputPath), 0755); err != nil {
			return fmt.Errorf("error creating output directory: %v", err)
		}

		// 创建输出文件
		outputFile, err := os.Create(fullOutputPath)
		if err != nil {
			return fmt.Errorf("error creating output file: %v", err)
		}
		defer outputFile.Close()

		// 执行模板
		if err := tmpl.Execute(outputFile, config); err != nil {
			return fmt.Errorf("error executing template: %v", err)
		}

		fmt.Printf("Generated: %s\n", outputPath)
	}

	return nil
}

func replaceVariables(path string, config *ServiceConfig) string {
	path = strings.ReplaceAll(path, "{{.ServiceName}}", config.ServiceName)
	path = strings.ReplaceAll(path, "{{.ServiceNameLower}}", config.ServiceNameLower)
	path = strings.ReplaceAll(path, "{{.ServiceNameTitle}}", config.ServiceNameTitle)
	path = strings.ReplaceAll(path, "{{.ServiceNameUpper}}", config.ServiceNameUpper)
	return path
}
